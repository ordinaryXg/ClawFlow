async function stopOpenClawGatewayBestEffort(reason: string): Promise<void> {
  const engine = getGlobalOpenClawCliEngine();
  try {
    const status = await Promise.race([
      engine.getGatewayStatus(),
      new Promise<'unknown'>((resolve) => setTimeout(() => resolve('unknown'), 1200)),
    ]);
    if (status !== 'running') return;
    await Promise.race([
      engine.stopGateway(),
      new Promise<void>((_resolve, reject) => setTimeout(() => reject(new Error('stopGateway timeout')), 8000)),
    ]);
  } catch (e: any) {
    console.warn(`[workspace] stopGateway (${reason}) failed (best-effort):`, e?.message || e);
  }
}
