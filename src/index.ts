function broadcastStickyDetachedPaths(): void {
  const paths = [...new Set(stickySatellitePathByWindowId.values())];
  BrowserWindow.getAllWindows().forEach((w) => {
    if (!w.isDestroyed()) w.webContents.send('sticky:detachedPaths', { paths });
  });
  try {
    rescheduleAllTodoTriggers();
  } catch {
    /* ignore */
  }
}

/** 主壳若仍指向刚拖出到卫星的工作区，则改记到下一个可用路径并通知各窗刷新（避免主窗 UI/IPC 仍停在已分离工作区） */
function bumpMainShellWorkspaceIfSameAsSatelliteBinding(detachedResolved: string): void {
  const last = getMainShellLastWorkspacePath();
  if (!last || !workspaceService.isSameWorkspacePath(last, detachedResolved)) return;

  const reg = workspaceService.loadRegistry();
  const recent = reg.recentWorkspacePaths ?? [];
  const def = workspaceService.getDefaultWorkspacePath();
  let next: string | null = null;
  for (const p of recent) {
    if (!workspaceService.isSameWorkspacePath(p, detachedResolved)) {
      next = path.resolve(p);
      break;
    }
  }
  if (!next && !workspaceService.isSameWorkspacePath(def, detachedResolved)) {
    next = path.resolve(def);
  }
  if (!next) next = path.resolve(def);

  setMainShellLastWorkspacePath(next);
  BrowserWindow.getAllWindows().forEach((w) => {
    if (!w.isDestroyed()) w.webContents.send('workspace:changed', { path: next });
  });
}

function applyWorkspaceForFocusedWindow(win: BrowserWindow | null): void {
  if (!win || win.isDestroyed()) return;
  const sat = stickySatellitePathByWindowId.get(win.id);
  const target = sat ?? getMainShellLastWorkspacePath();
  if (!target) return;
  const cur = getActiveWorkspaceRoot();
  if (workspaceService.isSameWorkspacePath(cur, target)) return;
  workspaceService.setActiveWorkspace(target);
  setActiveWorkspaceRoot(target);
  syncClawFlowEngineWorkspaceRoot(target);
  BrowserWindow.getAllWindows().forEach((w) => {
    if (!w.isDestroyed()) w.webContents.send('workspace:changed', { path: target });
  });
}

function registerShellViewWindowIPC(): void {
  try {
    ipcMain.removeHandler('window:setShellViewAppearance');
  } catch {
    /* first load or older Electron */
  }
  ipcMain.handle('window:setShellViewAppearance', (_event, params: { compact?: boolean }) => {
    const win = BrowserWindow.fromWebContents(_event.sender);
    if (!win || win.isDestroyed()) return { ok: false as const, error: 'no_window' };
    const wantCompact = Boolean(params?.compact);

    if (wantCompact) {
      if (!shellCompactByWindowId.has(win.id)) {
        const restoreMaximized = win.isMaximized();
        if (restoreMaximized) win.unmaximize();
        const restoreBounds = win.getBounds();
        shellCompactByWindowId.set(win.id, { restoreBounds, restoreMaximized });
      }
      const wa = screen.getDisplayMatching(win.getBounds()).workArea;
      /** 便签：宽约工作区 1/4；高度为工作区高度减去上下留白（略小于整屏高度），贴右侧竖条 */
      const width = Math.max(320, Math.floor(wa.width * 0.25));
      const marginTop = 10;
      const marginBottom = 18;
      const height = Math.max(420, wa.height - marginTop - marginBottom);
      const x = wa.x + wa.width - width;
      const y = wa.y + marginTop;
      win.setMinimumSize(260, 320);
      win.setBounds({ x, y, width, height }, true);
      return { ok: true as const };
    }

    const st = shellCompactByWindowId.get(win.id);
    if (st) {
      shellCompactByWindowId.delete(win.id);
      try {
        win.setMinimumSize(0, 0);
      } catch {
        /* ignore */
      }
      win.setBounds(st.restoreBounds, true);
      if (st.restoreMaximized) win.maximize();
    }
    return { ok: true as const };
  });
}

