function buildBaseBrowserWindow(): BrowserWindow {
  const win = new BrowserWindow({
    height: 800,
    width: 1200,
    /** 显式开启，避免部分平台/版本在无边框组合下误判为不可缩放 */
    resizable: true,
    movable: true,
    minimizable: true,
    maximizable: true,
    // Windows：无边框窗口，由页面内 Titlebar / 便签顶栏提供拖动与窗口按钮（无系统标题栏条）
    // Windows：透明 + 无边框时若保留 roundedCorners，DWM 常无法把桌面合成进来（表现为发灰/不透）。
    // 便签玻璃依赖 OS 级透明，故关闭系统圆角；界面圆角由页面 CSS 承担。
    // thickFrame：参与 Win32 边缘缩放（WS_THICKFRAME）；透明无边框曾出现边缘不可缩放回归（electron#48554），需较新 Chromium/Electron。
    ...(process.platform === 'win32'
      ? {
          frame: false,
          roundedCorners: false,
          transparent: true,
          backgroundColor: '#00000000',
          thickFrame: true,
        }
      : {}),
    webPreferences: {
      preload: MAIN_WINDOW_PRELOAD_WEBPACK_ENTRY,
      nodeIntegration: false,
      contextIsolation: true,
      webviewTag: true,
    },
  });

  if (!app.isPackaged) {
    win.webContents.on('before-input-event', (event, input) => {
      if (input.type !== 'keyDown') return;
      if (input.code !== 'F12' || !input.control || input.meta || input.alt) return;
      event.preventDefault();
      const wc = win.webContents;
      if (wc.isDevToolsOpened()) wc.closeDevTools();
      else wc.openDevTools({ mode: 'detach' });
    });
  }

  if (process.platform === 'win32') {
    try {
      win.setResizable(true);
    } catch {
      /* ignore */
    }
    try {
      win.setBackgroundColor('#00000000');
    } catch {
      /* ignore */
    }
  }

  if (process.platform === 'win32') {
    win.setMenuBarVisibility(false);
    win.removeMenu();
    win.setAutoHideMenuBar(true);
  }

  attachShellExternalLinkPolicy(win.webContents);

  win.on('focus', () => applyWorkspaceForFocusedWindow(win));
  return win;
}

registerStickySatelliteIPC({
  buildBrowserWindow: buildBaseBrowserWindow,
  mainWindowWebpackEntry: MAIN_WINDOW_WEBPACK_ENTRY,
  registerWindowControlIpcOnce,
  bumpMainShellWorkspaceIfSameAsSatelliteBinding,
  broadcastStickyDetachedPaths,
});

const createWindow = (): void => {
  registerWindowControlIpcOnce();
  const mainWindow = buildBaseBrowserWindow();
  mainWindow.loadURL(MAIN_WINDOW_WEBPACK_ENTRY);
};

// This method will be called when Electron has finished
// initialization and is ready to create browser windows.
// Some APIs can only be used after this event occurs.
app.whenReady().then(async () => {
  loadMainUiPrefsOnStartup();
  sanitizeAppCachePrefsOnStartupSync();
  workspaceService.migrateLegacyWorkspaceRegistryIfEmptySync();
  mergeLegacyWorkspacesTreesIntoEffectiveSync();
  const reg = workspaceService.loadRegistry();
  const rootsForTriad = new Set<string>();
  for (const p of reg.recentWorkspacePaths ?? []) {
    const r = path.resolve(String(p ?? '').trim());
    if (r) rootsForTriad.add(r);
  }
  if (reg.activeWorkspacePath) {
    const r = path.resolve(String(reg.activeWorkspacePath).trim());
    if (r) rootsForTriad.add(r);
  }
  migrateLegacyTriadForWorkspaceRootsSync([...rootsForTriad]);
  // 如果刚执行了“取消置顶 active”的一次性迁移，这里需要写回磁盘
  if (!reg.unpinActiveMigrated && reg.activeWorkspacePath) {
    workspaceService.saveRegistry({ ...reg, unpinActiveMigrated: true });
  }
  const activeRaw = reg.activeWorkspacePath?.trim() ? path.resolve(reg.activeWorkspacePath.trim()) : null;
  workspaceService.removeLegacyExternalAgentStateDirsSync();
  if (activeRaw) {
    await workspaceService.ensureWorkspaceInitialized(activeRaw);
  }
  try {
    const { ensureSystemAgentsInitialized } = await import('./main/system-agents/system-agent-roster-bootstrap');
    const tools = activeRaw ? await workspaceService.readWorkspaceToolManifest(activeRaw) : null;
    await ensureSystemAgentsInitialized(Boolean(tools?.skills));
  } catch (e: unknown) {
    console.warn('[system-agents] init failed:', e instanceof Error ? e.message : e);
  }
  if (activeRaw) {
    applyActiveWorkspace(activeRaw);
    setMainShellLastWorkspacePath(activeRaw);
  } else {
    clearActiveWorkspaceRootInMemory();
  }

  registerWorkspaceIPC();
  try {
    rescheduleAllTodoTriggers();
  } catch (e: unknown) {
    console.warn('[todoTriggers] initial schedule failed:', e instanceof Error ? e.message : e);
  }
  const webSearchProvider = String(process.env.CLAWFLOW_WEB_SEARCH_PROVIDER ?? 'searxng').toLowerCase();
  registerClawFlowIPC({
    workspaceRoot: activeRaw ?? undefined,
    verbose: false,
    webSearch: {
      enabled: process.env.CLAWFLOW_WEB_SEARCH_DISABLED === '1' ? false : undefined,
      provider:
        webSearchProvider === 'brave' ||
        webSearchProvider === 'duckduckgo' ||
        webSearchProvider === 'searxng' ||
        webSearchProvider === 'bocha'
          ? webSearchProvider
          : 'auto',
      braveApiKey: process.env.BRAVE_API_KEY,
      braveBaseUrl: process.env.BRAVE_BASE_URL,
      bochaApiKey: process.env.BOCHA_API_KEY,
      bochaBaseUrl: process.env.BOCHA_BASE_URL,
      searxngBaseUrl: process.env.CLAWFLOW_SEARXNG_URL,
      searxngApiKey: process.env.CLAWFLOW_SEARXNG_API_KEY,
    },
  });
  registerGatewayIPC();
  // Phase 3: keep internal GatewayDaemon resident (best-effort)
  try {
    await getGatewayDaemon().start();
  } catch (e: any) {
    console.warn('[GatewayDaemon] auto-start failed:', e?.message ?? e);
  }
  registerAppSettingsIPC();
  setupApplicationMenu();

  createWindow();
  restartLarkBridgeFromPrefs();
});

app.on('before-quit', () => {
  stopLarkBridge();
  destroyAppTray();
});

// Quit when all windows are closed, except on macOS. There, it's common
// for applications and their menu bar to stay active until the user quits
// explicitly with Cmd + Q.
app.on('window-all-closed', () => {
  if (process.platform === 'darwin') return;
  if (getMainUiPrefs().closeButtonAction === 'minimizeToTray') {
    return;
  }
  app.quit();
});

app.on('activate', () => {
  // On OS X it's common to re-create a window in the app when the
  // dock icon is clicked and there are no other windows open.
  if (BrowserWindow.getAllWindows().length === 0) {
    createWindow();
  }
});

