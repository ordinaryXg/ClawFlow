let windowControlIpcRegistered = false;

function registerWindowControlIpcOnce(): void {
  if (windowControlIpcRegistered) return;
  windowControlIpcRegistered = true;
  ipcMain.handle('window:minimize', (event) => BrowserWindow.fromWebContents(event.sender)?.minimize());
  ipcMain.handle('window:toggleMaximize', (event) => {
    const win = BrowserWindow.fromWebContents(event.sender);
    if (!win) return;
    if (win.isMaximized()) win.unmaximize();
    else win.maximize();
  });
  ipcMain.handle('window:close', (event) => {
    const win = BrowserWindow.fromWebContents(event.sender);
    if (!win || win.isDestroyed()) return;
    const prefs = getMainUiPrefs();
    if (prefs.closeButtonAction === 'minimizeToTray') {
      win.hide();
      if (process.platform === 'win32' || process.platform === 'linux') {
        try {
          ensureAppTray(
            () => getAppLanguage(),
            () => {
              destroyAppTray();
              app.quit();
            }
          );
        } catch (e) {
          console.warn('[app-tray] ensure failed:', e);
        }
      }
      return;
    }
    win.close();
  });
  ipcMain.handle('window:reload', (event) => BrowserWindow.fromWebContents(event.sender)?.webContents.reload());
  ipcMain.handle('window:toggleDevTools', (event) => {
    const wc = BrowserWindow.fromWebContents(event.sender)?.webContents;
    if (!wc) return;
    if (wc.isDevToolsOpened()) wc.closeDevTools();
    else wc.openDevTools({ mode: 'detach' });
  });
  ipcMain.handle('window:undo', (event) => BrowserWindow.fromWebContents(event.sender)?.webContents.undo());
  ipcMain.handle('window:redo', (event) => BrowserWindow.fromWebContents(event.sender)?.webContents.redo());
  ipcMain.handle('window:cut', (event) => BrowserWindow.fromWebContents(event.sender)?.webContents.cut());
  ipcMain.handle('window:copy', (event) => BrowserWindow.fromWebContents(event.sender)?.webContents.copy());
  ipcMain.handle('window:paste', (event) => BrowserWindow.fromWebContents(event.sender)?.webContents.paste());
  ipcMain.handle('window:selectAll', (event) => BrowserWindow.fromWebContents(event.sender)?.webContents.selectAll());
  ipcMain.handle('app:syncMainUiPrefs', (_e, payload: unknown) => {
    const o = payload && typeof payload === 'object' ? (payload as Record<string, unknown>) : {};
    const a = o.closeButtonAction === 'minimizeToTray' ? 'minimizeToTray' : 'quit';
    saveMainUiPrefs({ closeButtonAction: a });
    return { ok: true as const };
  });
  ipcMain.handle('app:quit', () => app.quit());
  ipcMain.handle('app:relaunch', () => {
    app.relaunch();
    app.exit(0);
  });
}

function buildBaseBrowserWindow(): BrowserWindow {
  const win = new BrowserWindow({
    height: 800,
    width: 1200,
    /** 显式开启，避免部分平台/版本在无边框组合下误判为不可缩放 */
    resizable: true,
    movable: true,
    minimizable: true,
    maximizable: true,
    // Windows：无边框窗口，由页面内 Titlebar / 便签顶栏提供拖动与窗口按钮（无系统标题栏条）
    // Windows：透明 + 无边框时若保留 roundedCorners，DWM 常无法把桌面合成进来（表现为发灰/不透）。
    // 便签玻璃依赖 OS 级透明，故关闭系统圆角；界面圆角由页面 CSS 承担。
    // thickFrame：参与 Win32 边缘缩放（WS_THICKFRAME）；透明无边框曾出现边缘不可缩放回归（electron#48554），需较新 Chromium/Electron。
    ...(process.platform === 'win32'
      ? {
          frame: false,
          roundedCorners: false,
          transparent: true,
          backgroundColor: '#00000000',
          thickFrame: true,
        }
      : {}),
    webPreferences: {
      preload: MAIN_WINDOW_PRELOAD_WEBPACK_ENTRY,
      nodeIntegration: false,
      contextIsolation: true,
      webviewTag: true,
    },
  });

  if (!app.isPackaged) {
    win.webContents.on('before-input-event', (event, input) => {
      if (input.type !== 'keyDown') return;
      if (input.code !== 'F12' || !input.control || input.meta || input.alt) return;
      event.preventDefault();
      const wc = win.webContents;
      if (wc.isDevToolsOpened()) wc.closeDevTools();
      else wc.openDevTools({ mode: 'detach' });
    });
  }

  if (process.platform === 'win32') {
    try {
      win.setResizable(true);
    } catch {
      /* ignore */
    }
    try {
      win.setBackgroundColor('#00000000');
    } catch {
      /* ignore */
    }
  }

  if (process.platform === 'win32') {
    win.setMenuBarVisibility(false);
    win.removeMenu();
    win.setAutoHideMenuBar(true);
  }

  win.on('focus', () => applyWorkspaceForFocusedWindow(win));
  return win;
}

function registerStickySatelliteIPC(): void {
  const rm = (channel: string) => {
    try {
      ipcMain.removeHandler(channel);
    } catch {
      /* first load */
    }
  };
  rm('sticky:getBootstrap');
  rm('sticky:getDetachedPaths');
  rm('sticky:openSatellite');
  rm('sticky:mergeSatellite');

  ipcMain.handle('sticky:getBootstrap', (event) => {
    const win = BrowserWindow.fromWebContents(event.sender);
    if (!win) return { role: 'main' as const, satelliteWorkspace: null as string | null };
    const p = stickySatellitePathByWindowId.get(win.id) ?? null;
    return { role: p ? ('satellite' as const) : ('main' as const), satelliteWorkspace: p };
  });

  ipcMain.handle('sticky:getDetachedPaths', () => ({
    paths: [...new Set(stickySatellitePathByWindowId.values())],
  }));

  ipcMain.handle('sticky:openSatellite', async (_event, params: { workspacePath?: string }) => {
    const raw = String(params?.workspacePath ?? '').trim();
    if (!raw) return { ok: false as const, error: 'missing_path' };
    const resolved = path.resolve(raw);
    for (const w of BrowserWindow.getAllWindows()) {
      if (w.isDestroyed()) continue;
      const p = stickySatellitePathByWindowId.get(w.id);
      if (p && workspaceService.isSameWorkspacePath(p, resolved)) {
        bumpMainShellWorkspaceIfSameAsSatelliteBinding(resolved);
        w.focus();
        return { ok: true as const, focused: true as const };
      }
    }
    registerWindowControlIpcOnce();
    const win = buildBaseBrowserWindow();
    stickySatellitePathByWindowId.set(win.id, resolved);
    win.on('closed', () => {
      stickySatellitePathByWindowId.delete(win.id);
      broadcastStickyDetachedPaths();
    });
    win.loadURL(MAIN_WINDOW_WEBPACK_ENTRY);
    win.once('ready-to-show', () => {
      try {
        win.show();
        win.focus();
      } catch {
        /* ignore */
      }
    });
    broadcastStickyDetachedPaths();
    bumpMainShellWorkspaceIfSameAsSatelliteBinding(resolved);
    return { ok: true as const, focused: false as const };
  });

  ipcMain.handle('sticky:mergeSatellite', async (_event, params: { workspacePath?: string }) => {
    const raw = String(params?.workspacePath ?? '').trim();
    if (!raw) return { ok: false as const, error: 'missing_path' };
    const resolved = path.resolve(raw);
    const hit = [...stickySatellitePathByWindowId.entries()].find(([, p]) =>
      workspaceService.isSameWorkspacePath(p, resolved)
    );
    if (!hit) return { ok: true as const, closed: false as const };
    const [winId] = hit;
    const win = BrowserWindow.getAllWindows().find((w) => w.id === winId && !w.isDestroyed());
    win?.close();
    return { ok: true as const, closed: true as const };
  });
}

