function registerWorkspaceIPC(): void {
  ipcMain.handle('workspace:getActive', async () => {
    const root = getActiveWorkspaceRoot();
    const meta = workspaceService.readWorkspaceMetaSync(root);
    return { path: root, meta };
  });

  ipcMain.handle('workspace:listRecent', async () => {
    return workspaceService.loadRegistry().recentWorkspacePaths;
  });

  ipcMain.handle('workspace:getDefaultPath', async () => workspaceService.getDefaultWorkspacePath());

  ipcMain.handle('workspace:remove', async (_event, folderPath: string) => {
    const res = await workspaceService.removeWorkspaceForUser(String(folderPath || ''));
    if (!res.ok) return res;
    setActiveWorkspaceRoot(res.newActivePath);
    syncClawFlowEngineWorkspaceRoot(res.newActivePath);
    BrowserWindow.getAllWindows().forEach((w) =>
      w.webContents.send('workspace:changed', { path: res.newActivePath })
    );
    await workspaceService.ensureWorkspaceInitialized(res.newActivePath);
    void getGlobalOpenClawCliEngine()
      .stopGateway()
      .catch((e) => console.warn('[workspace] stopGateway after remove (best-effort) failed:', e?.message || e));
    return res;
  });

  ipcMain.handle('workspace:setActive', async (_event, nextPath: string) => {
    const resolved = path.resolve(String(nextPath || ''));
    workspaceService.setActiveWorkspace(resolved);
    setActiveWorkspaceRoot(resolved);
    syncClawFlowEngineWorkspaceRoot(resolved);
    BrowserWindow.getAllWindows().forEach((w) => w.webContents.send('workspace:changed', { path: resolved }));
    // 等待初始化完成（含根目录角色模板），避免 UI 已切换但文件尚未写入
    try {
      await workspaceService.ensureWorkspaceInitialized(resolved);
    } catch (e: unknown) {
      const msg = e instanceof Error ? e.message : String(e);
      console.warn('[workspace] ensureWorkspaceInitialized failed:', msg);
    }
    void getGlobalOpenClawCliEngine()
      .stopGateway()
      .catch((e) => console.warn('[workspace] stopGateway (best-effort) failed:', e?.message || e));
    return { success: true, path: resolved };
  });

  /** 拖入文件夹到「+」：校验为目录后初始化并切为当前工作区 */
  ipcMain.handle('workspace:addFromAbsolutePath', async (_e, absPath: string) => {
    const resolved = path.resolve(String(absPath || ''));
    let st: fs.Stats | null;
    try {
      st = await fs.promises.stat(resolved);
    } catch {
      return { ok: false as const, error: 'not_found' };
    }
    if (!st.isDirectory()) {
      return { ok: false as const, error: 'not_directory' };
    }
    try {
      await workspaceService.ensureWorkspaceInitialized(resolved);
    } catch (e: unknown) {
      const msg = e instanceof Error ? e.message : String(e);
      return { ok: false as const, error: msg };
    }
    workspaceService.setActiveWorkspace(resolved);
    setActiveWorkspaceRoot(resolved);
    syncClawFlowEngineWorkspaceRoot(resolved);
    BrowserWindow.getAllWindows().forEach((w) => w.webContents.send('workspace:changed', { path: resolved }));
    void getGlobalOpenClawCliEngine()
      .stopGateway()
      .catch((e) => console.warn('[workspace] stopGateway (best-effort) failed:', e?.message || e));
    return { ok: true as const, path: resolved };
  });

  ipcMain.handle('workspace:pickFolder', async (event) => {
    const win = BrowserWindow.fromWebContents(event.sender);
    return await workspaceService.pickWorkspaceFolder(win);
  });

  ipcMain.handle(
    'workspace:ensureInitialized',
    async (_e, folderPath: string, opts?: { tools?: WorkspaceToolSelection }) => {
      const meta = await workspaceService.ensureWorkspaceInitialized(String(folderPath || ''), opts);
      return { meta };
    }
  );

  ipcMain.handle('workspace:getToolSelection', async (_e, folderPath: string) => {
    try {
      const tools = await workspaceService.readWorkspaceToolManifest(String(folderPath || ''));
      return { ok: true as const, tools };
    } catch (e: unknown) {
      const msg = e instanceof Error ? e.message : String(e);
      return { ok: false as const, error: msg };
    }
  });

  ipcMain.handle('workspace:setToolSelection', async (_e, folderPath: string, tools: WorkspaceToolSelection) => {
    try {
      await workspaceService.writeWorkspaceToolSelection(String(folderPath || ''), tools ?? {});
      return { ok: true as const };
    } catch (e: unknown) {
      const msg = e instanceof Error ? e.message : String(e);
      return { ok: false as const, error: msg };
    }
  });

  ipcMain.handle('workspace:listDir', async (_e, relativePath?: string) => {
    const root = getActiveWorkspaceRoot();
    try {
      const entries = await workspaceExplorer.listWorkspaceDirectory(root, String(relativePath ?? ''));
      return { ok: true as const, entries };
    } catch (e: unknown) {
      const msg = e instanceof Error ? e.message : String(e);
      return { ok: false as const, error: msg, entries: [] as Array<{ name: string; kind: 'file' | 'dir' }> };
    }
  });

  ipcMain.handle('workspace:readFilePreview', async (_e, relativePath: string) => {
    const root = getActiveWorkspaceRoot();
    return await workspaceExplorer.readWorkspaceFilePreview(root, String(relativePath ?? ''));
  });

  const resolveAbs = (root: string, rel: string) => workspaceExplorer.resolvePathInsideWorkspace(root, String(rel ?? ''));

  ipcMain.handle('workspace:resolveAbsolutePath', async (_e, relativePath: string) => {
    const root = getActiveWorkspaceRoot();
    const rel = String(relativePath ?? '');
    const abs = resolveAbs(root, rel);
    return { ok: true as const, workspaceRoot: root, relativePath: rel, absolutePath: abs };
  });

  ipcMain.handle('workspace:revealInExplorer', async (_e, relativePath: string) => {
    const root = getActiveWorkspaceRoot();
    const rel = String(relativePath ?? '');
    const abs = resolveAbs(root, rel);
    try {
      shell.showItemInFolder(abs);
      return { ok: true as const };
    } catch (e: unknown) {
      const msg = e instanceof Error ? e.message : String(e);
      return { ok: false as const, error: msg };
    }
  });

  ipcMain.handle('clipboard:writeText', async (_e, text: string) => {
    try {
      clipboard.writeText(String(text ?? ''));
      return { ok: true as const };
    } catch (e: unknown) {
      const msg = e instanceof Error ? e.message : String(e);
      return { ok: false as const, error: msg };
    }
  });

  ipcMain.handle('workspace:mkdir', async (_e, params: { relativePath: string }) => {
    const root = getActiveWorkspaceRoot();
    const rel = String(params?.relativePath ?? '');
    const abs = resolveAbs(root, rel);
    try {
      await fs.promises.mkdir(abs, { recursive: true });
      return { ok: true as const };
    } catch (e: unknown) {
      const msg = e instanceof Error ? e.message : String(e);
      return { ok: false as const, error: msg };
    }
  });

  ipcMain.handle(
    'workspace:writeTextFile',
    async (_e, params: { relativePath: string; content?: string; overwrite?: boolean }) => {
      const root = getActiveWorkspaceRoot();
      const rel = String(params?.relativePath ?? '');
      const abs = resolveAbs(root, rel);
      const content = String(params?.content ?? '');
      const overwrite = params?.overwrite !== false;
      try {
        await fs.promises.mkdir(path.dirname(abs), { recursive: true });
        const exists = await fs.promises
          .stat(abs)
          .then((s) => s.isFile() || s.isSymbolicLink())
          .catch(() => false);
        if (exists && !overwrite) return { ok: false as const, error: 'File exists (overwrite=false)' };
        await fs.promises.writeFile(abs, content, 'utf8');
        return { ok: true as const };
      } catch (e: unknown) {
        const msg = e instanceof Error ? e.message : String(e);
        return { ok: false as const, error: msg };
      }
    }
  );

  ipcMain.handle('workspace:renamePath', async (_e, params: { from: string; to: string; overwrite?: boolean }) => {
    const root = getActiveWorkspaceRoot();
    const fromRel = String(params?.from ?? '');
    const toRel = String(params?.to ?? '');
    const overwrite = params?.overwrite === true;
    const fromAbs = resolveAbs(root, fromRel);
    const toAbs = resolveAbs(root, toRel);
    try {
      await fs.promises.mkdir(path.dirname(toAbs), { recursive: true });
      const toExists = await fs.promises
        .stat(toAbs)
        .then(() => true)
        .catch(() => false);
      if (toExists && !overwrite) return { ok: false as const, error: 'Destination exists (overwrite=false)' };
      if (toExists && overwrite) await fs.promises.rm(toAbs, { recursive: true, force: true });
      await fs.promises.rename(fromAbs, toAbs);
      return { ok: true as const };
    } catch (e: unknown) {
      const msg = e instanceof Error ? e.message : String(e);
      return { ok: false as const, error: msg };
    }
  });

  ipcMain.handle('workspace:deletePath', async (_e, params: { relativePath: string }) => {
    const root = getActiveWorkspaceRoot();
    const rel = String(params?.relativePath ?? '').trim();
    if (!rel) {
      return { ok: false as const, error: 'empty_path' };
    }
    let abs: string;
    try {
      abs = resolveAbs(root, rel);
    } catch (e: unknown) {
      const msg = e instanceof Error ? e.message : String(e);
      return { ok: false as const, error: msg };
    }
    try {
      await fs.promises.rm(abs, { recursive: true, force: true });
      return { ok: true as const };
    } catch (e: unknown) {
      const msg = e instanceof Error ? e.message : String(e);
      return { ok: false as const, error: msg };
    }
  });

  ipcMain.handle('workspace:getChangeLog', async (_e, limit?: number) => {
    const root = getActiveWorkspaceRoot();
    const lim = typeof limit === 'number' && Number.isFinite(limit) ? limit : 100;
    const entries = await workspaceChangeLog.getWorkspaceChangeLog(root, lim);
    return { ok: true as const, entries };
  });

  ipcMain.handle(
    'workspace:appendChangeLog',
    async (_e, payload: { conversationId: string; userPreview: string; assistantExcerpt: string }) => {
      const root = getActiveWorkspaceRoot();
      try {
        const entry = await workspaceChangeLog.appendWorkspaceChangeLog(root, {
          conversationId: String(payload?.conversationId ?? ''),
          userPreview: String(payload?.userPreview ?? ''),
          assistantExcerpt: String(payload?.assistantExcerpt ?? ''),
        });
        return { ok: true as const, entry };
      } catch (e: unknown) {
        const msg = e instanceof Error ? e.message : String(e);
        return { ok: false as const, error: msg };
      }
    }
  );
}

const createWindow = (): void => {
  // Create the browser window.
  const mainWindow = new BrowserWindow({
    height: 800,
    width: 1200,
    // Windows：无边框窗口，由页面内 Titlebar / 便签顶栏提供拖动与窗口按钮（无系统标题栏条）
    // Windows：透明 + 无边框时若保留 roundedCorners，DWM 常无法把桌面合成进来（表现为发灰/不透）。
    // 便签玻璃依赖 OS 级透明，故关闭系统圆角；界面圆角由页面 CSS 承担。
    ...(process.platform === 'win32'
      ? {
          frame: false,
          roundedCorners: false,
          transparent: true,
          backgroundColor: '#00000000',
        }
      : {}),
    webPreferences: {
      preload: MAIN_WINDOW_PRELOAD_WEBPACK_ENTRY,
      nodeIntegration: false,
      contextIsolation: true,
      webviewTag: true,
    },
  });

  // 开发模式：Ctrl+F12 切换开发者工具（不注册全局快捷键，仅在窗口聚焦时生效）
  if (!app.isPackaged) {
    mainWindow.webContents.on('before-input-event', (event, input) => {
      if (input.type !== 'keyDown') return;
      if (input.code !== 'F12' || !input.control || input.meta || input.alt) return;
      event.preventDefault();
      const wc = mainWindow.webContents;
      if (wc.isDevToolsOpened()) wc.closeDevTools();
      else wc.openDevTools({ mode: 'detach' });
    });
  }

  // 再强调一次窗口底色，避免部分显卡/主题下初始帧为不透明白底
  if (process.platform === 'win32') {
    try {
      mainWindow.setBackgroundColor('#00000000');
    } catch {
      /* ignore */
    }
  }

  // and load the index.html of the app.
  mainWindow.loadURL(MAIN_WINDOW_WEBPACK_ENTRY);

  // Windows：无边框下仍隐藏菜单栏
  if (process.platform === 'win32') {
    mainWindow.setMenuBarVisibility(false);
    mainWindow.removeMenu();
    mainWindow.setAutoHideMenuBar(true);
  }

  // window controls for custom titlebar
  ipcMain.handle('window:minimize', (event) => BrowserWindow.fromWebContents(event.sender)?.minimize());
  ipcMain.handle('window:toggleMaximize', (event) => {
    const win = BrowserWindow.fromWebContents(event.sender);
    if (!win) return;
    if (win.isMaximized()) win.unmaximize();
    else win.maximize();
  });
  ipcMain.handle('window:close', (event) => BrowserWindow.fromWebContents(event.sender)?.close());

  // common actions (for custom titlebar menus)
  ipcMain.handle('window:reload', (event) => BrowserWindow.fromWebContents(event.sender)?.webContents.reload());
  ipcMain.handle('window:toggleDevTools', (event) => {
    const wc = BrowserWindow.fromWebContents(event.sender)?.webContents;
    if (!wc) return;
    if (wc.isDevToolsOpened()) wc.closeDevTools();
    else wc.openDevTools({ mode: 'detach' });
  });
  ipcMain.handle('window:undo', (event) => BrowserWindow.fromWebContents(event.sender)?.webContents.undo());
  ipcMain.handle('window:redo', (event) => BrowserWindow.fromWebContents(event.sender)?.webContents.redo());
  ipcMain.handle('window:cut', (event) => BrowserWindow.fromWebContents(event.sender)?.webContents.cut());
  ipcMain.handle('window:copy', (event) => BrowserWindow.fromWebContents(event.sender)?.webContents.copy());
  ipcMain.handle('window:paste', (event) => BrowserWindow.fromWebContents(event.sender)?.webContents.paste());
  ipcMain.handle('window:selectAll', (event) => BrowserWindow.fromWebContents(event.sender)?.webContents.selectAll());
  ipcMain.handle('app:quit', () => app.quit());
};

// This method will be called when Electron has finished
// initialization and is ready to create browser windows.
// Some APIs can only be used after this event occurs.
app.whenReady().then(async () => {
  const reg = workspaceService.loadRegistry();
  // 如果刚执行了“取消置顶 active”的一次性迁移，这里需要写回磁盘
  if (!reg.unpinActiveMigrated && reg.activeWorkspacePath) {
    workspaceService.saveRegistry({ ...reg, unpinActiveMigrated: true });
  }
  const active = reg.activeWorkspacePath ?? workspaceService.getDefaultWorkspacePath();
  workspaceService.migrateWorkspaceOpenclawToGlobalOnce();
  workspaceService.removeLegacyWorkspaceOpenclawDirs();
  await workspaceService.ensureWorkspaceInitialized(active);
  workspaceService.setActiveWorkspace(active);
  setActiveWorkspaceRoot(active);

  registerWorkspaceIPC();
  registerOpenClawIPC();
  const webSearchProvider = String(process.env.CLAWFLOW_WEB_SEARCH_PROVIDER ?? 'auto').toLowerCase();
  registerClawFlowIPC({
    workspaceRoot: active,
    verbose: true,
    webSearch: {
      enabled: process.env.CLAWFLOW_WEB_SEARCH_DISABLED === '1' ? false : undefined,
      provider:
        webSearchProvider === 'brave' || webSearchProvider === 'duckduckgo'
          ? webSearchProvider
          : 'auto',
      braveApiKey: process.env.BRAVE_API_KEY,
    },
  });
  registerGatewayIPC();
  // Phase 3: keep internal GatewayDaemon resident (best-effort)
  try {
    await getGatewayDaemon().start();
  } catch (e: any) {
    console.warn('[GatewayDaemon] auto-start failed:', e?.message ?? e);
  }
  ipcMain.handle('skillMarket:getIndex', async (_e, opts?: { forceRefresh?: boolean }) => {
    try {
      return await fetchSkillMarketIndex({ forceRefresh: Boolean(opts?.forceRefresh) });
    } catch (e: unknown) {
      const msg = e instanceof Error ? e.message : String(e);
      console.warn('[skillMarket:getIndex]', msg);
      return { ok: false as const, error: msg || 'skill market handler failed' };
    }
  });
  ipcMain.handle('app:getVersion', () => app.getVersion());
  ipcMain.handle('app:setLanguage', (_event, lang: string) => {
    currentLang = String(lang).toLowerCase().startsWith('en') ? 'en' : 'zh';
    setupApplicationMenu();
    return { success: true };
  });
  setupApplicationMenu();

  createWindow();
});

// Quit when all windows are closed, except on macOS. There, it's common
// for applications and their menu bar to stay active until the user quits
// explicitly with Cmd + Q.
app.on('window-all-closed', () => {
  if (process.platform !== 'darwin') {
    app.quit();
  }
});

app.on('activate', () => {
  // On OS X it's common to re-create a window in the app when the
  // dock icon is clicked and there are no other windows open.
  if (BrowserWindow.getAllWindows().length === 0) {
    createWindow();
  }
});

